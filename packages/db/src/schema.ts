import {
  pgTable,
  uuid,
  varchar,
  text,
  bigint,
  boolean,
  timestamp,
  jsonb,
  pgEnum,
} from 'drizzle-orm/pg-core';
export const mediaType = pgEnum('media_type', ['photo', 'video', 'audio']);
export const assets = pgTable('assets', {
  id: uuid('id').primaryKey().defaultRandom(),
  title: varchar('title', { length: 200 }).notNull(),
  filename: varchar('filename', { length: 255 }).notNull(),
  type: mediaType('type').notNull(),
  mime: varchar('mime', { length: 120 }).notNull(),
  size: bigint('size', { mode: 'number' }).notNull(),
  source: varchar('source', { length: 16 }).$type<'local' | 'demo' | 'upload'>().notNull(),
  sourcePath: text('source_path'),
  width: bigint('width', { mode: 'number' }),
  height: bigint('height', { mode: 'number' }),
  capturedAt: timestamp('captured_at', { withTimezone: true, mode: 'string' }).notNull(),
  tags: jsonb('tags').$type<string[]>().notNull().default([]),
  description: text('description').notNull().default(''),
  favorite: boolean('favorite').notNull().default(false),
  location: text('location').notNull().default(''),
  collectionId: varchar('collection_id', { length: 100 }),
  collectionName: varchar('collection_name', { length: 100 }),
  customMetadata: jsonb('custom_metadata').$type<Record<string, string>>().notNull().default({}),
  destinationId: varchar('destination_id', { length: 100 }),
  objectKey: text('object_key'),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
});
